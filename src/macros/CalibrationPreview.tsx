export function CalibrationPreview({ kind, className = '', compact = false }: CalibrationPreviewProps) {
  const rows = (compact ? COMPACT_PREVIEWS : PREVIEWS)[kind].trim().split('\n')
  return (
    <svg
      className={`calibration-preview${compact ? ' calibration-preview--compact' : ''} ${className}`}
      viewBox={compact ? '0 0 48 40' : '0 0 96 80'}
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      {rows.flatMap((row, y) => Array.from(row, (cell, x) => cell === '#'
        ? <circle key={`${x}-${y}`} cx={x * 4 + 2} cy={y * 4 + 2} r="1.2" />
        : null))}
    </svg>
  )
}
